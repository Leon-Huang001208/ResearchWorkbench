/** Real fixture login, shared/personal approval UI and role-boundary checks. */
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const origin = 'http://127.0.0.1:18992';
const root = process.env.RESEARCH_PLUGIN_GATEWAY_FIXTURE_ROOT;
const native = process.env.RESEARCH_PLUGIN_FIXTURE_ROOT;
assert.ok(root?.startsWith('/tmp/rwb-plugin-gateway-'));
assert.ok(native?.startsWith('/tmp/rwb-plugin-browser-'));
const users = JSON.parse(await readFile(root + '/fixture-users.json', 'utf8'));
const {chromium} = await import(pathToFileURL(process.env.RESEARCH_PLAYWRIGHT_MODULE));
const browser = await chromium.launch({headless:true, executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const evidence = {fixture:true, identity:'real temporary AccountStore and gateway cookies', tenantRuntime:'separate mocked DSH/native API fixture; no production accounts or services', checks:[]};
try {
  const adminContext = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await adminContext.newPage();
  await page.goto(origin + '/auth');
  await page.locator('input[name="username"]').fill('plugin-admin');
  await page.locator('input[name="password"]').fill('fixture-admin-safe-2026-10-22');
  await page.getByRole('button',{name:'登录',exact:true}).click();
  await page.waitForURL(value => value.pathname === '/');
  await page.goto(origin + '/#/skills?kind=plugin');
  await page.getByRole('heading',{name:'插件',exact:true}).waitFor();
  await page.getByLabel('导入固定版本插件 ZIP').setInputFiles(native + '/fixture-plugin.zip');
  await page.getByRole('button',{name:'安全预览，不执行代码'}).click();
  await page.locator('.plugin-version strong').filter({hasText:'fixture'}).waitFor();
  await page.getByRole('button',{name:'选择本版本全部权限'}).click();
  await page.getByRole('button',{name:'审核并授权所选权限'}).click();
  await page.getByText('已记录此摘要的明确权限审核。',{exact:true}).waitFor();
  await page.getByRole('button',{name:'启用此已审版本'}).click();
  await page.getByText('审批分发状态已保存；请空闲时应用到当前实例，查看 Host 实际就绪状态。',{exact:true}).waitFor();
  await page.screenshot({path:'outputs/plugin-browser/04-shared-admin.png',fullPage:true});
  await page.getByLabel('审批范围').selectOption('personal');
  await page.getByLabel('导入固定版本插件 ZIP').setInputFiles(root + '/personal-plugin.zip');
  await page.getByRole('button',{name:'安全预览，不执行代码'}).click();
  await page.locator('.plugin-version strong').filter({hasText:'personal-fixture'}).waitFor();
  await page.getByRole('button',{name:'选择本版本全部权限'}).click();
  await page.getByRole('button',{name:'审核并授权所选权限'}).click();
  await page.getByText('已记录此摘要的明确权限审核。',{exact:true}).waitFor();
  const own = await (await adminContext.request.get(origin + '/api/server/plugins/personal')).json();
  assert.equal(own.items[0].name,'personal-fixture');
  evidence.checks.push('real admin login, shared import/review/distribution, separate personal approval namespace');
  const readerContext = await browser.newContext({viewport:{width:1280,height:900}});
  const reader = await readerContext.newPage();
  await reader.goto(origin + '/auth');
  await reader.locator('input[name="username"]').fill('plugin-reader');
  await reader.locator('input[name="password"]').fill('fixture-reader-safe-2026-10-22');
  await reader.getByRole('button',{name:'登录',exact:true}).click();
  await reader.waitForURL(value => value.pathname === '/');
  await reader.goto(origin + '/#/skills?kind=plugin');
  await reader.getByText('仅管理员可导入、审核和分发插件。你可以查看支持状态，并为已批准的 MCP 配置自己的凭据与会话授权。',{exact:true}).waitFor();
  assert.equal(await reader.locator('[data-plugin-import]').count(),0);
  assert.equal(await reader.locator('[data-plugin-action="review"]').count(),0);
  const denied = await readerContext.request.post(origin + '/api/server/plugins/shared/preview',{headers:{Origin:origin,'X-RWB-Page-User':users.reader,'X-RWB-Role':'admin'},multipart:{file:{name:'plugin.zip',mimeType:'application/zip',buffer:await readFile(native + '/fixture-plugin.zip')}}});
  assert.equal(denied.status(),403);
  assert.equal((await denied.json()).error.code,'administrator_required');
  const other = await readerContext.request.get(origin + '/api/server/plugins/personal?owner=' + users.admin);
  assert.equal(other.status(),403);
  await reader.getByLabel('审批范围').selectOption('personal');
  await reader.getByText('尚无插件。导入后可逐项查看权限与不支持的组件。',{exact:true}).waitFor();
  await reader.screenshot({path:'outputs/plugin-browser/05-personal-reader.png',fullPage:true});
  evidence.checks.push('real reader login, admin actions absent, spoofed role rejected by gateway, another personal owner denied, own namespace empty');
  await writeFile('outputs/plugin-browser/server-evidence.json',JSON.stringify(evidence,null,2));
  console.log(JSON.stringify(evidence));
} finally {await browser.close();}
