/** Isolated capability-center UI against real local APIs and bounded fixture Hosts. */
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const url = process.env.RESEARCH_PLUGIN_BROWSER_URL || 'http://127.0.0.1:18991';
const fixture = process.env.RESEARCH_PLUGIN_FIXTURE_ROOT;
assert.ok(fixture?.startsWith('/tmp/rwb-plugin-browser-'), 'Only the test-owned fixture root is accepted');
assert.equal(new URL(url).hostname, '127.0.0.1');
const module = process.env.RESEARCH_PLAYWRIGHT_MODULE;
assert.ok(module, 'Use an existing playwright-core module; never install dependencies');
const { chromium } = await import(pathToFileURL(module));
const output = resolve(process.env.RESEARCH_PLUGIN_BROWSER_OUTPUT || 'outputs/plugin-browser');
await mkdir(output, {recursive: true});
const browser = await chromium.launch({headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const pageErrors = [];
const evidence = {fixture: true, checks: []};
try {
  const context = await browser.newContext({viewport: {width: 1440, height: 1000}, acceptDownloads: true});
  const page = await context.newPage();
  page.on('pageerror', error => pageErrors.push(error.message));
  await page.route('**/*', async route => new URL(route.request().url()).origin === url ? route.continue() : route.abort());
  await page.goto(url + '/#/skills?kind=plugin');
  await page.getByRole('heading', {name: '插件', exact: true}).waitFor();
  await page.getByRole('button', {name: '安全预览，不执行代码'}).waitFor();
  await page.getByLabel('导入固定版本插件 ZIP').setInputFiles(fixture + '/fixture-plugin.zip');
  await page.getByRole('button', {name: '安全预览，不执行代码'}).click();
  await page.locator('.plugin-version strong').filter({hasText: 'fixture'}).waitFor();
  assert.equal(await page.getByRole('button', {name: '审核并授权所选权限'}).isDisabled(), true);
  assert.ok((await page.locator('.plugin-components').innerText()).includes('mcp / canary'));
  await page.screenshot({path: output + '/01-preview.png', fullPage: true});
  evidence.checks.push('capability center tab, bounded ZIP preview, support table and initially unchecked permissions');
  await page.getByRole('button', {name: '选择本版本全部权限'}).click();
  await page.getByRole('button', {name: '审核并授权所选权限'}).click();
  await page.getByText('已记录此摘要的明确权限审核。', {exact: true}).waitFor();
  await page.getByRole('button', {name: '启用此已审版本'}).click();
  await page.getByText('Host 投影状态已更新；原生发现和会话授权单独显示。', {exact: true}).waitFor();
  assert.ok(await page.locator('[data-plugin-reason="native_discovery_pending"]').count() >= 3);
  evidence.checks.push('digest-bound approval, native CapabilityCatalog projection and truthful unconfirmed discovery');
  await page.getByRole('button', {name: '生成原生安装预览'}).click();
  await page.getByRole('heading', {name: '确认此固定安装计划'}).waitFor();
  assert.equal(await page.locator('[data-plugin-mcp-install] input[type="password"]').count(), 0, 'offline canary requires no supplier credentials');
  await page.getByRole('button', {name: '确认原生安装', exact: true}).click();
  await page.getByText('原生安装已完成；探测和实际 schema 审核仍待执行。', {exact: true}).waitFor();
  assert.equal(await page.locator('[data-plugin-mcp-install]').count(), 0);
  await page.getByRole('button', {name: '探测已安装组件'}).click();
  await page.getByRole('button', {name: '查看当前工具与审批快照'}).click();
  await page.getByRole('heading', {name: '实际安装与工具快照'}).waitFor();
  await page.getByRole('button', {name: '审核并锁定这份工具 schema'}).click();
  await page.getByText('已锁定实际字节、配置与 schema。', {exact: true}).waitFor();
  await page.getByRole('button', {name: '空闲时启用 MCP'}).click();
  await page.getByText('MCP：enabled', {exact: true}).waitFor();
  const audit = await (await context.request.get(url + '/__fixture/audit')).json();
  assert.equal(audit.installations, 1);
  assert.equal(audit.native_methods.includes('session.prompt'), false);
  assert.equal(audit.host, 'SDKHost');
  assert.equal(audit.no_models_binding_updates, 1);
  evidence.checks.push('native MCP preview/confirm/probe, exact artifact/config/schema review and activation through real MCPRuntimeService and SDKHost with an explicit no-model binding callback');
  await page.screenshot({path: output + '/02-mcp.png', fullPage: true});
  await page.getByRole('button', {name: '停用 MCP', exact: true}).click();
  await page.getByText('MCP：disabled', {exact: true}).waitFor();
  await page.getByRole('button', {name: '撤权并停用', exact: true}).click();
  await page.getByText('Host 投影状态已更新；原生发现和会话授权单独显示。', {exact: true}).waitFor();
  await page.getByLabel('导入固定版本插件 ZIP').setInputFiles(fixture + '/fixture-plugin-v2.zip');
  await page.getByRole('button', {name: '安全预览，不执行代码'}).click();
  await page.locator('.plugin-version').filter({hasText: 'v2.0.0'}).waitFor();
  await page.getByRole('button', {name: '选择本版本全部权限'}).click();
  await page.getByRole('button', {name: '审核并授权所选权限'}).click();
  await page.getByText('已记录此摘要的明确权限审核。', {exact: true}).waitFor();
  await page.getByRole('button', {name: '启用此已审版本'}).click();
  await page.getByText('Host 投影状态已更新；原生发现和会话授权单独显示。', {exact: true}).waitFor();
  await page.locator('.plugin-version').filter({hasText: 'v1.0.0'}).click();
  await page.getByRole('button', {name: '回滚到此已审版本'}).click();
  await page.getByText('Host 投影状态已更新；原生发现和会话授权单独显示。', {exact: true}).waitFor();
  const packages = await (await context.request.get(url + '/api/research/plugins')).json();
  assert.equal(packages.items.find(item => item.enabled).version, '1.0.0');
  evidence.checks.push('withdrawal, reviewed upgrade and rollback actually change current native package projection');
  await page.screenshot({path: output + '/03-rollback.png', fullPage: true});
  const capabilities = await (await context.request.get(url + '/api/research/capabilities')).json();
  const method = capabilities.items.find(item => item.kind === 'method' && item.enabled && item.version);
  const skill = capabilities.items.find(item => item.id === 'document-reading' && item.enabled && item.version);
  const workflow = capabilities.items.find(item => item.kind === 'workflow' && !item.metadata?.report_workflow);
  assert.ok(method && skill && workflow, 'the real fixture catalog supplies each legacy kind');
  await page.goto(url + '/#/skills');
  await page.locator('.capability-workspace-card').filter({hasText: method.name}).waitFor();
  assert.deepEqual(await page.locator('[aria-label="能力类型"] [role="tab"]').allTextContents(), ['技能', '连接器', '插件']);
  for (const item of [method, skill, workflow]) assert.equal(await page.locator('.capability-workspace-card').filter({hasText: item.name}).count(), 1);
  await page.screenshot({path: output + '/04-unified-skills.png', fullPage: true});
  await page.locator('.capability-workspace-card').filter({hasText: method.name}).scrollIntoViewIfNeeded();
  await page.screenshot({path: output + '/04b-legacy-method-cards.png', fullPage: true});
  await page.locator(`[data-use-skill="${skill.id}"]`).click();
  await page.locator('[data-clear-capability]').waitFor();
  assert.ok((await page.locator('.capability-chips').innerText()).includes(skill.name));
  await page.goto(url + '/#/skills?kind=method');
  await page.locator(`[data-use-method="${method.id}"]`).click();
  await page.locator(`[data-remove-method="${method.id}"]`).waitFor();
  assert.ok((await page.locator('.capability-chips').innerText()).includes(skill.name));
  assert.equal(await page.locator('.method-picker, [data-method-id]').count(), 0);
  await page.screenshot({path: output + '/05-skill-and-method-draft.png', fullPage: true});
  evidence.checks.push('three primary categories, real Skill/Workflow/Method unified cards, and method_ids selection preserves primary skill without sending');
  for (const kind of ['workflow', 'method']) {
    await page.goto(url + '/#/skills?kind=' + kind);
    await page.locator('.capability-workspace-card').filter({hasText: method.name}).waitFor();
    assert.equal(await page.locator('#capability-kind-skill').getAttribute('aria-selected'), 'true');
  }
  await page.goto(url + '/#/skills?kind=connector');
  await page.getByRole('heading', {name: 'MCP 连接器', exact: true}).waitFor();
  assert.equal(await page.locator('[data-tool-detail]').count(), 0, 'default connector cards do not become a naked tool directory');
  await page.getByRole('searchbox', {name: '搜索连接器'}).fill('Excel');
  assert.ok((await page.locator('[aria-label="本机连接器"]').innerText()).includes('Excel'));
  await page.getByRole('searchbox', {name: '搜索连接器'}).fill('');
  await page.screenshot({path: output + '/06-connectors.png', fullPage: true});
  await page.goto(url + '/#/skills?kind=tool');
  await page.getByText('旧工具链接 · 工具声明', {exact: true}).waitFor();
  const firstTool = page.locator('[data-tool-detail]').first();
  const toolID = await firstTool.getAttribute('data-tool-detail');
  await firstTool.click();
  await page.getByRole('dialog', {name: /.+/}).waitFor();
  await page.getByRole('button', {name: '进入管理', exact: true}).click();
  await page.getByRole('heading', {name: /.+/}).first().waitFor();
  assert.equal(await page.locator('[aria-label="只读工具详情"]').count(), 1);
  assert.ok((await page.locator('[aria-label="只读工具详情"]').innerText()).includes(toolID));
  await page.screenshot({path: output + '/07-tool-detail.png', fullPage: true});
  for (const [suffix, heading] of [['kind=data', 'DataHub 数据能力'], ['kind=data&view=connections', 'DataHub 数据源'], ['kind=tool&view=market', 'MCP 市场'], ['view=connections', '本机集成']]) {
    await page.goto(url + '/#/skills?' + suffix);
    await page.locator('#capability-kind-connector[aria-selected="true"]').waitFor();
    await page.getByRole('heading', {name: heading, exact: true}).waitFor();
    if (heading === 'MCP 市场') await page.screenshot({path: output + '/09-legacy-mcp-market.png', fullPage: true});
  }
  await page.goto(url + '/#/skills?kind=workflow&view=plans');
  await page.getByRole('heading', {name: '定时任务', exact: true}).first().waitFor();
  await page.goto(url + '/#/automations');
  await page.getByRole('heading', {name: '定时任务', exact: true}).first().waitFor();
  assert.equal(await page.locator('a.rail-link.active[href="#/automations"]').count(), 1);
  await page.screenshot({path: output + '/08-automations.png', fullPage: true});
  evidence.checks.push('connector search by real local label, MCP/DataHub/local cards, contextual read-only tool detail, legacy links and independent timer route');
  const finalAudit = await (await context.request.get(url + '/__fixture/audit')).json();
  assert.equal(finalAudit.model_prompts, 0);
  evidence.audit = finalAudit;
  assert.deepEqual(pageErrors, []);
  evidence.pageErrors = pageErrors;
  evidence.modelPrompts = 0;
  await writeFile(output + '/evidence.json', JSON.stringify(evidence, null, 2));
  console.log(JSON.stringify(evidence));
} catch (error) {
  await writeFile(output + '/failure.json', JSON.stringify({message: error.message, stack: error.stack, pageErrors}, null, 2));
  for (const context of browser.contexts()) for (const page of context.pages()) await page.screenshot({path: output + '/failure.png', fullPage: true}).catch(() => {});
  throw error;
} finally { await browser.close(); }
