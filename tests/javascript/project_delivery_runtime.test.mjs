import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {verifyProjectDeliveryRuntime, loadProjectDeliveryRuntime} from '../../scripts/project_delivery_runtime.mjs';

const runtimeRoot = fileURLToPath(new URL('../../scripts/vendor/leon-engineering/', import.meta.url));

test('the project pin loads its real controller and detects altered or missing dependencies', async t => {
  assert.equal(verifyProjectDeliveryRuntime().valid, true);
  assert.equal(typeof (await loadProjectDeliveryRuntime()).startDelivery, 'function');
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'rwb-runtime-pin-')));
  t.after(() => fs.rmSync(root, {recursive: true, force: true}));
  const copy = path.join(root, 'runtime');
  fs.cpSync(runtimeRoot, copy, {recursive: true});
  assert.equal(verifyProjectDeliveryRuntime({runtimeRoot: copy}).valid, true);
  const alternate = path.join(root, 'lib/resources/lifecycle.mjs');
  fs.mkdirSync(path.dirname(alternate), {recursive: true});
  fs.writeFileSync(alternate, 'throw new Error("unverified engine");');
  assert.throws(() => verifyProjectDeliveryRuntime({runtimeRoot: copy}), {code: 'DELIVERY_RUNTIME_UNVERIFIED'});
  fs.unlinkSync(alternate);
  const kernel = path.join(copy, 'lib/resources/lifecycle.mjs');
  fs.appendFileSync(kernel, '\n// changed\n');
  assert.throws(() => verifyProjectDeliveryRuntime({runtimeRoot: copy}), {code: 'DELIVERY_RUNTIME_UNVERIFIED'});
  fs.copyFileSync(path.join(runtimeRoot, 'lib/resources/lifecycle.mjs'), kernel);
  fs.unlinkSync(path.join(copy, 'harness-storage.mjs'));
  assert.throws(() => verifyProjectDeliveryRuntime({runtimeRoot: copy}), {code: 'DELIVERY_RUNTIME_UNVERIFIED'});
});

test('real controller resumes legacy receipts and reports CI failure with global runtime inaccessible', t => {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'rwb-runtime-isolated-')));
  t.after(() => fs.rmSync(root, {recursive: true, force: true}));
  const project = path.join(root, 'project'), remote = path.join(root, 'remote.git');
  fs.mkdirSync(project);
  const git = (cwd, args) => {
    const result = spawnSync('/usr/bin/git', ['-c', 'gc.auto=0', '-c', 'maintenance.auto=false', '-C', cwd, ...args], {encoding: 'utf8'});
    assert.equal(result.status, 0, result.stderr);
    return result.stdout.trim();
  };
  git(root, ['init', '--bare', '-b', 'master', remote]);
  git(project, ['init', '-b', 'master']);
  git(project, ['config', 'user.name', 'Fixture']);
  git(project, ['config', 'user.email', 'fixture@example.invalid']);
  fs.writeFileSync(path.join(project, 'tracked.txt'), 'base\n');
  git(project, ['add', '.']); git(project, ['commit', '-m', 'base']);
  git(project, ['remote', 'add', 'origin', remote]); git(project, ['push', '-u', 'origin', 'master']);
  const script = path.join(root, 'isolated.mjs');
  const loader = new URL('../../scripts/project_delivery_runtime.mjs', import.meta.url).href;
  fs.writeFileSync(script, `import fs from 'node:fs';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {loadProjectDeliveryRuntime} from ${JSON.stringify(loader)};
assert.throws(() => fs.readFileSync(${JSON.stringify(path.join(os.homedir(), '.agents/leon-engineering/runtime/iteration-delivery.mjs'))}), {code: 'ERR_ACCESS_DENIED'});
const controller = await loadProjectDeliveryRuntime();
const projectRoot = ${JSON.stringify(project)};
let receipt = controller.startDelivery({projectRoot, taskId: 'legacy', slug: 'pin', worktreeRoot: ${JSON.stringify(path.join(root, 'worktrees'))}});
const file = ${JSON.stringify(path.join(project, '.git/leon-engineering/deliveries/legacy.json'))};
const original = fs.readFileSync(file);
assert.equal(controller.readDeliveryReceipt({projectRoot, taskId: 'legacy'}).schemaVersion, 1);
assert.deepEqual(fs.readFileSync(file), original);
const git = (cwd, args) => {
  const result = spawnSync('/usr/bin/git', ['-c', 'gc.auto=0', '-c', 'maintenance.auto=false', '-C', cwd, ...args], {encoding: 'utf8'});
  assert.equal(result.status, 0, result.stderr);
  return result.stdout.trim();
};
fs.writeFileSync(receipt.featureWorktree + '/feature.txt', 'feature');
git(receipt.featureWorktree, ['add', '.']); git(receipt.featureWorktree, ['commit', '-m', 'feature']);
receipt = controller.prepareDelivery({projectRoot, taskId: 'legacy', integrationWorktreeRoot: ${JSON.stringify(path.join(root, 'integration'))}});
const priorCandidate = receipt.integrationCommit;
fs.writeFileSync(projectRoot + '/parallel.txt', 'parallel');
git(projectRoot, ['add', '.']); git(projectRoot, ['commit', '-m', 'parallel']); git(projectRoot, ['push', 'origin', 'master']);
git(receipt.integrationWorktree, ['rev-parse', 'HEAD']);
assert.throws(() => controller.publishDelivery({projectRoot, taskId: 'legacy', verification: {command: 'git rev-parse HEAD', status: 'passed', durationSeconds: 0}}), /remote default branch moved/);
receipt = controller.prepareDelivery({projectRoot, taskId: 'legacy', integrationWorktreeRoot: ${JSON.stringify(path.join(root, 'integration'))}});
assert.notEqual(receipt.integrationCommit, priorCandidate);
assert.equal(receipt.status, 'prepared');
assert.throws(() => controller.publishDelivery({projectRoot, taskId: 'legacy'}), /verification evidence is required/);
assert.ok(receipt.integrationHistory.some(item => item.commit === priorCandidate));
receipt.status = 'awaiting_ci'; receipt.integrationCommit = receipt.baseCommit;
fs.writeFileSync(file, JSON.stringify(receipt));
const failed = controller.refreshDeliveryStatus({projectRoot, taskId: 'legacy', resolveCiStatus: () => ({status: 'failed', runs: []})});
assert.equal(failed.status, 'ci_failed');
console.log(JSON.stringify({status: 'passed', legacySchema: receipt.schemaVersion, ci: failed.ci.status}));
`);
  const scripts = fileURLToPath(new URL('../../scripts/', import.meta.url));
  const permissionFlag = process.allowedNodeEnvironmentFlags.has('--permission') ? '--permission' : '--experimental-permission';
  const result = spawnSync(process.execPath, [permissionFlag, `--allow-fs-read=${root}`, `--allow-fs-read=${scripts}`, `--allow-fs-write=${root}`, '--allow-child-process', script], {encoding: 'utf8', timeout: 30000});
  assert.equal(result.status, 0, result.stderr);
  assert.deepEqual(JSON.parse(result.stdout), {status: 'passed', legacySchema: 1, ci: 'failed'});
});
