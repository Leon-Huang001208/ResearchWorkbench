DRY_RUN = "--dry-run" in sys.argv


def main() -> int:
    print("=" * 60)
    print("静态股票列表 → stock_master 种子脚本")
    print("=" * 60)
    print(f"模式: {'DRY RUN' if DRY_RUN else 'WRITE'}")
    print(f"股票数量: {len(MAJOR_A_SHARES)}")

    from data_layer.repositories.base import db_session
    from data_layer.repositories.market_data_repository import MarketDataRepository

    if DRY_RUN:
        print("\n将插入以下股票:")
        for symbol, name, industry in MAJOR_A_SHARES[:10]:
            print(f"  {symbol} {name} ({industry})")
        print(f"  ... 共 {len(MAJOR_A_SHARES)} 只")
        return 0

    with db_session() as db:
        market_repo = MarketDataRepository(db)

        items = []
        for symbol, name, industry in MAJOR_A_SHARES:
            parts = symbol.split(".")
            raw_code = parts[0]
            exchange = parts[1] if len(parts) > 1 else None
            items.append(
                {
                    "symbol": symbol,
                    "raw_code": raw_code,
                    "name": name,
                    "exchange": exchange,
                    "market": "A-share",
                    "industry_level1": industry,
                    "industry_level2": None,
                    "industry_level3": None,
                    "list_date": None,
                    "source": "static_seed",
                }
            )

        try:
            result = market_repo.upsert_stock_master_many(items)
            print(f"\n✅ 完成: 插入/更新 {result} 条记录")
        except Exception as e:
            print(f"\n❌ 失败: {e}")
            logger.error(f"seed_stock_master_static failed: {e}", exc_info=True)
            return 1

    print(f"\n现在搜索索引覆盖 {len(MAJOR_A_SHARES)} 只主要 A 股标的。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
