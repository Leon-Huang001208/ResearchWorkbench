import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {randomBytes,randomUUID} from 'node:crypto';
import postgres from 'postgres';
import {migrate,ingestPage} from '../src/database.ts';
import {initializeIdentity,activateRuntime} from '../src/control.ts';
import {openQueue,processOne,superviseOwner} from '../src/queue.ts';
import {parseFeed} from '../src/feed.ts';
import {registerProcessing,scheduleProcessing,processingHandler,canonicalGroupingInput,appliedGroupingResult,type GroupingModel} from '../src/processing.ts';
import {provisionModelBudget,reserveModel,markModelDispatch,saveModelReceipt} from '../src/model-budget.ts';
import {sha256} from '../src/material.ts';
import {correctEvent} from '../src/events.ts';

test('durable material processing blocks without model and atomically applies saved grouping receipts',{timeout:20000},async()=>{
  const dir=resolve(import.meta.dirname,'../../../logs/hot-stage-zero');
  const receipt=JSON.parse(await readFile(join(dir,'receipt.json'),'utf8')),password=await readFile(join(dir,'password'),'utf8');
  const db=postgres({host:'127.0.0.1',port:receipt.port,database:'hot_probe',username:'postgres',password,onnotice:()=>{}});
  const schema='hot_processing_'+randomBytes(5).toString('hex');let boss:Awaited<ReturnType<typeof openQueue>>|undefined;
  try{
    await migrate(db,schema);const instance=randomUUID(),token=randomBytes(32).toString('hex');
    await initializeIdentity(db,schema,instance,token);let owner=await activateRuntime(db,schema,instance,token,'native');
    boss=await openQueue(db,schema,true);
    await db`insert into ${db(schema)}.sources(id,operator,config) values('fed','Federal Reserve','{}'::jsonb)`;
    const raw=await readFile(join(dir,'fed.xml'),'utf8'),acquiredAt=new Date();
    const items=parseFeed(raw,'https://www.federalreserve.gov/feeds/press_all.xml',acquiredAt).slice(0,2);
    const stored=await ingestPage(db,{source:'fed',raw,acquiredAt,materials:items,cursor:{}},schema);
    await db.begin(tx=>registerProcessing(tx,schema,stored.materialIds));
    await db.begin(tx=>registerProcessing(tx,schema,stored.materialIds));
    assert.equal((await db`select count(*)::int n from ${db(schema)}.processing_items`)[0].n,2);
    assert.equal(await scheduleProcessing(db,boss,schema,owner,false),0);
    assert.equal((await db`select count(*)::int n from ${db(schema)}.job where name='hot.process'`)[0].n,0);
    await provisionModelBudget(db,schema,{scopeId:'synthetic-processing',authorizationHash:sha256('test-only'),maxCalls:5,maxTokens:100,maxCostMicros:0,
      daily:{maxCalls:5,maxTokens:100,maxCostMicros:0,timezone:'Asia/Shanghai'}});
    let calls=0,sameTarget:string|null=null,simulateCrash=false;
    const model:GroupingModel={async run(packet,signal){
      signal.throwIfAborted();
      if(sameTarget)assert.ok(packet.candidates.some(c=>c.id===sameTarget),'English original matches an existing Chinese event through original report evidence');
      const decision={parts:[{relation:sameTarget?'same_occurrence' as const:'different_event' as const,candidateId:sameTarget,title:'中文归组事件',reason:'Synthetic occurrence fixture'}]};
      const key=sha256(canonicalGroupingInput(packet));
      const reserved=await reserveModel(db,schema,owner,'synthetic-processing',{resultKey:key,specHash:key,maxTokens:10,maxCostMicros:0});
      if(reserved.state==='reused')return {resultKey:key,decision:JSON.parse((reserved.response as any).text)};
      assert.equal(reserved.state,'reserved');if(reserved.state!=='reserved')throw Error('fixture');calls++;
      await markModelDispatch(db,schema,owner,reserved.ticket);
      await saveModelReceipt(db,schema,reserved.ticket,{text:JSON.stringify(decision)},{tokens:1,costMicros:0,providerRequestId:null,costBasis:'synthetic'});
      if(simulateCrash){simulateCrash=false;owner=await activateRuntime(db,schema,instance,token,'native');}
      return {resultKey:key,decision};
    }};
    assert.equal(await scheduleProcessing(db,boss,schema,owner,true),2);
    const handler=processingHandler(db,schema,owner,model);
    for(let i=0;i<2;i++)assert.equal(await processOne(boss,db,schema,owner,'hot.process',handler),'completed');
    assert.equal(calls,2);
    assert.equal((await db`select count(*)::int n from ${db(schema)}.events`)[0].n,2);
    assert.equal((await db`select count(*)::int n from ${db(schema)}.processing_items where state='applied'`)[0].n,2);
    assert.equal(await scheduleProcessing(db,boss,schema,owner,true),0);
    assert.equal(await processOne(boss,db,schema,owner,'hot.process',handler),'idle');
    await assert.rejects(db`update ${db(schema)}.processing_items set packet='{}'::jsonb where state='applied'`);
    const [original]=await db`select event_ids from ${db(schema)}.processing_results where material_id=${stored.materialIds[0]}`;sameTarget=original.event_ids[0];
    const [firstMaterial]=await db`select original_url from ${db(schema)}.materials where id=${stored.materialIds[0]}`;
    const fixture={...items.find(item=>item.url===firstMaterial.original_url)!,url:'https://example.com/duplicate-'+randomUUID()};
    const extra=await ingestPage(db,{source:'fed',raw,acquiredAt:new Date(),materials:[fixture],cursor:{}},schema);
    await db.begin(tx=>registerProcessing(tx,schema,extra.materialIds));
    await boss.updateQueue('hot.process',{expireInSeconds:1});
    await scheduleProcessing(db,boss,schema,owner,true);simulateCrash=true;
    const previous=owner;
    await assert.rejects(processOne(boss,db,schema,previous,'hot.process',processingHandler(db,schema,previous,model)),/owner_stale/);
    assert.equal(calls,3);assert.equal((await db`select count(*)::int n from ${db(schema)}.events`)[0].n,2);
    await db`select pg_sleep(1.15)`;await superviseOwner(db,schema,owner,'hot.process');
    await scheduleProcessing(db,boss,schema,owner,true);
    assert.equal(await processOne(boss,db,schema,owner,'hot.process',processingHandler(db,schema,owner,model)),'completed');
    assert.equal(calls,3,'saved receipt reused across generation restart');
    assert.equal((await db`select count(*)::int n from ${db(schema)}.events`)[0].n,2);
    assert.equal((await db`select current_revision from ${db(schema)}.events where id=${sameTarget}`)[0].current_revision,2);
    const staleFixture={...fixture,url:'https://example.com/stale-'+randomUUID()};
    const stale=await ingestPage(db,{source:'fed',raw,acquiredAt:new Date(),materials:[staleFixture],cursor:{}},schema);
    await db.begin(tx=>registerProcessing(tx,schema,stale.materialIds));await scheduleProcessing(db,boss,schema,owner,true);
    const changingModel:GroupingModel={async run(packet,signal){const value=await model.run(packet,signal);
      await correctEvent(db,schema,owner,randomUUID(),'Human title changed during model dispatch',{type:'title',id:sameTarget!,expected:2,title:'人工更新'});return value;}};
    assert.equal(await processOne(boss,db,schema,owner,'hot.process',processingHandler(db,schema,owner,changingModel)),'completed');
    assert.equal((await db`select state from ${db(schema)}.processing_items where material_id=${stale.materialIds[0]}`)[0].state,'stale');
    const [claim]=await db`select result from ${db(schema)}.job_claims where input_key like ${'hot.process:'+stale.materialIds[0]+':%'}`;
    assert.equal(claim.result.state,'stale');assert.equal(await scheduleProcessing(db,boss,schema,owner,true),0);
    const blocked=await ingestPage(db,{source:'fed',raw,acquiredAt:new Date(),materials:[{...fixture,url:'https://example.com/budget-'+randomUUID()}],cursor:{}},schema);
    await db.begin(tx=>registerProcessing(tx,schema,blocked.materialIds));await scheduleProcessing(db,boss,schema,owner,true);
    assert.equal(await processOne(boss,db,schema,owner,'hot.process',processingHandler(db,schema,owner,{run:async()=>{throw Error('hot_model_budget_exhausted');}})),'failed');
    assert.equal((await db`select state from ${db(schema)}.processing_items where material_id=${blocked.materialIds[0]}`)[0].state,'blocked_budget');
    assert.equal(await scheduleProcessing(db,boss,schema,owner,true),0);
    const rejected=await ingestPage(db,{source:'fed',raw,acquiredAt:new Date(),materials:[{...fixture,url:'https://example.com/rejected-'+randomUUID()}],cursor:{}},schema);
    await db.begin(tx=>registerProcessing(tx,schema,rejected.materialIds));await scheduleProcessing(db,boss,schema,owner,true);
    await db`create function ${db(schema)}.reject_fixture_event() returns trigger language plpgsql as
      'BEGIN RAISE EXCEPTION ''hot_event_fixture_rejected''; END'`;
    await db`create trigger reject_fixture_event before insert on ${db(schema)}.event_versions for each row execute function ${db(schema)}.reject_fixture_event()`;
    assert.equal(await processOne(boss,db,schema,owner,'hot.process',processingHandler(db,schema,owner,model)),'completed');
    assert.equal((await db`select state,result_key from ${db(schema)}.processing_items where material_id=${rejected.materialIds[0]}`)[0].state,'rejected');
    assert.equal((await db`select current_revision from ${db(schema)}.events where id=${sameTarget}`)[0].current_revision,3);
    assert.equal((await db`select count(*)::int n from ${db(schema)}.processing_results where material_id=${rejected.materialIds[0]}`)[0].n,0);
    assert.equal(await scheduleProcessing(db,boss,schema,owner,true),0,'deterministic rejected publication never auto-requeues');
    assert.equal((await appliedGroupingResult(db,schema,stored.materialIds[0],1))!.material_revision,1);
    const originalItem=items.find(item=>item.url===firstMaterial.original_url)!;
    await ingestPage(db,{source:'fed',raw,acquiredAt:new Date(),materials:[{...originalItem,title:originalItem.title+' corrected fixture'}],cursor:{}},schema);
    await db.begin(tx=>registerProcessing(tx,schema,[stored.materialIds[0]]));
    assert.equal((await db`select current_revision from ${db(schema)}.materials where id=${stored.materialIds[0]}`)[0].current_revision,2);
    assert.equal(await appliedGroupingResult(db,schema,stored.materialIds[0],2),null,'revision 1 result cannot certify revision 2');
  }finally{if(boss)await boss.stop();await db.end({timeout:5});}
});
